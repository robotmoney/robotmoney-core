#!/usr/bin/env bash
# Self-test for the nested struct rule of scripts/ci/check-core-storage-layout.sh (Deploy 4 v0.9.0 upgrade audit,
# regression test 1). Release v0.9.0 changed Request, Settlement (FlowQueue state) and StepParams (Rebalancer) in the
# middle and the gate passed, because it pinned an ERC-7201 namespace as flat source lines.
#
# The cases, on the committed snapshots (no forge, no chain):
#   a. the committed layout extends the v0.8.0 baseline with the migrations file: the three breaks are declared;
#   b. without the migrations entries the same comparison fails and names each struct and member; removing one
#      entry fails for that struct alone;
#   c. synthetic layouts: a mid-struct insert, a reorder, a removal and a retype fail and name the member; an append
#      in the free bytes of the last slot or in a new slot passes; an array-element struct may not change size; a
#      migrations entry covers a break only with the right contract, struct and hashes.
# With --live (CI, after `forge build`) the same a. and b. also run through the gate itself, which reads the live
# layout from forge and the namespace structs from the probe contracts.
#
# The baseline contracts/test/fixtures/storage-layout/baselines/v0.8.0 is the `nested` section of the five fund
# proxies at fa7c47182 (contracts 0.8.0, live as Deploy 4). It was generated by this gate's --write in an export of
# that commit with contracts/test/helpers/StorageLayoutProbe.sol added (its two fund imports pointed at
# contracts/test/prototype/src/lib, where the fund sources lived). The other sections of that output were identical
# to the snapshots committed at fa7c47182.
#
# Usage: scripts/ci/check-core-storage-layout.test.sh [--live]
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
GATE="$HERE/check-core-storage-layout.sh"
PY="$HERE/storage_layout_nested.py"
SNAP="$REPO/contracts/test/fixtures/storage-layout"
BASE="$SNAP/baselines/v0.8.0"
MIG="$HERE/storage-layout-migrations.json"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

LIVE=0
[[ "${1:-}" == "--live" ]] && LIVE=1

ran=0
pass() { ran=$((ran + 1)); echo "ok   $1"; }
bad() { echo "FAIL $1" >&2; [[ -s "$TMP/out" ]] && sed 's/^/     /' "$TMP/out" >&2; exit 1; }

# check <live> <base> <contract> [migrations]: runs the struct rule, output in $TMP/out, sets rc.
check() {
  rc=0
  python3 "$PY" check --live "$1" --base "$2" --contract "$3" --migrations "${4:-$TMP/none.json}" --ref base >"$TMP/out" 2>&1 || rc=$?
}
# want <exit> <label> [text]...: the last check exited <exit> and its output holds every text.
want() {
  local code="$1" label="$2" text
  shift 2
  [[ "$rc" == "$code" ]] || bad "$label: exit $rc, wanted $code"
  for text in "$@"; do
    grep -qF -- "$text" "$TMP/out" || bad "$label: the output does not say '$text'"
  done
  pass "$label"
}

echo '{"migrations":[]}' >"$TMP/none.json"

# ── a. the committed tree extends v0.8.0 with the migrations file ─────────────────────────────────────────────
for c in FlowQueue Rebalancer RebalancerV2 RebalanceGovernance RobotMoneyFund; do
  [[ -s "$BASE/$c.json" ]] || bad "the v0.8.0 baseline of $c is missing"
  check "$SNAP/$c.json" "$BASE/$c.json" "$c" "$MIG"
  case "$c" in
    FlowQueue) want 0 "a. FlowQueue extends v0.8.0 with the declared migrations" \
      "struct Request breaks the layout" "struct Settlement breaks the layout" "FlowQueue.migrateV090" ;;
    Rebalancer | RebalancerV2) want 0 "a. $c extends v0.8.0 with the declared migration" \
      "struct StepParams breaks the layout" "Rebalancer.migrateV090" ;;
    *) want 0 "a. $c extends v0.8.0 and declares no break"
      [[ ! -s "$TMP/out" ]] || bad "a. $c needed a migration, none is expected" ;;
  esac
done
# The namespace structs are pinned with members, slot and offset: Request sits behind a mapping of FlowState.
jq -e '.nested["robotmoney.storage.FlowQueue"]["t_struct(Request)_storage"].members
       | length > 0 and all(.[]; has("label") and has("slot") and has("offset") and has("type"))' "$SNAP/FlowQueue.json" >/dev/null \
  || bad "the FlowQueue snapshot does not pin the members of Request"
pass "the FlowQueue snapshot pins Request member by member"
jq -e '.nested["robotmoney.storage.FlowQueue"]["t_struct(FlowState)_storage"].members | length > 0' "$SNAP/FlowQueue.json" >/dev/null \
  || bad "the FlowQueue snapshot does not pin the namespace root FlowState"
pass "the FlowQueue snapshot pins the namespace root struct with slots"
jq -e '.nested.storage["t_struct(StepParams)_storage"].members | length > 0' "$SNAP/Rebalancer.json" >/dev/null \
  || bad "the Rebalancer snapshot does not pin the members of StepParams"
pass "the Rebalancer snapshot pins StepParams member by member"

# ── b. without the migrations entries the v0.9.0 breaks fail ──────────────────────────────────────────────────
check "$SNAP/FlowQueue.json" "$BASE/FlowQueue.json" FlowQueue
want 1 "b. FlowQueue fails against v0.8.0 with no migrations entry" \
  "struct Request: member limit" "struct Settlement: member depositBoundPrice" "no migration declared for FlowQueue"
check "$SNAP/Rebalancer.json" "$BASE/Rebalancer.json" Rebalancer
want 1 "b. Rebalancer fails against v0.8.0 with no migrations entry" "struct StepParams: member keeperGrace" "was removed"
for s in Request Settlement; do
  jq --arg s "$s" '.migrations |= map(select(.struct != $s))' "$MIG" >"$TMP/less.json"
  check "$SNAP/FlowQueue.json" "$BASE/FlowQueue.json" FlowQueue "$TMP/less.json"
  want 1 "b. removing the $s entry fails for $s" "struct $s: member"
  other="Settlement"; [[ "$s" == "Settlement" ]] && other="Request"
  grep -q "struct $other: member" "$TMP/out" && bad "b. the $other entry stopped covering $other"
  pass "b. the $other entry still covers $other"
done
jq '.migrations |= map(select(.struct != "StepParams"))' "$MIG" >"$TMP/less.json"
check "$SNAP/Rebalancer.json" "$BASE/Rebalancer.json" Rebalancer "$TMP/less.json"
want 1 "b. removing the StepParams entries fails for StepParams" "struct StepParams: member keeperGrace"
# An entry is bound to both hashes: the declared break does not cover a further change of the same struct.
jq '.nested["robotmoney.storage.FlowQueue"]["t_struct(Request)_storage"].members[1].type = "t_uint8"' "$SNAP/FlowQueue.json" >"$TMP/live.json"
check "$TMP/live.json" "$BASE/FlowQueue.json" FlowQueue "$MIG"
want 1 "b. a declared break does not cover a different new layout of the struct" "struct Request: member"

# ── c. synthetic layouts ──────────────────────────────────────────────────────────────────────────────────────
# T: two packed words then a full slot. U: half a slot, free bytes after it. E: an array element.
cat >"$TMP/base.json" <<'JSON'
{"nested": {"storage": {
  "t_struct(T)_storage": {"bytes": 64, "arrayElement": false, "members": [
    {"label": "a", "slot": "0", "offset": 0, "type": "t_uint64"},
    {"label": "b", "slot": "0", "offset": 8, "type": "t_uint64"},
    {"label": "c", "slot": "1", "offset": 0, "type": "t_uint256"}]},
  "t_struct(U)_storage": {"bytes": 32, "arrayElement": false, "members": [
    {"label": "x", "slot": "0", "offset": 0, "type": "t_uint128"}]},
  "t_struct(E)_storage": {"bytes": 32, "arrayElement": true, "members": [
    {"label": "p", "slot": "0", "offset": 0, "type": "t_uint128"}]}
}}}
JSON
T='.nested.storage["t_struct(T)_storage"]'
U='.nested.storage["t_struct(U)_storage"]'
E='.nested.storage["t_struct(E)_storage"]'
synth() { jq "$1" "$TMP/base.json" >"$TMP/live.json"; check "$TMP/live.json" "$TMP/base.json" Synthetic "${2:-}"; }

synth '.'
want 0 "c. an identical layout passes"
synth "$T.members |= (.[:1] + [{label: \"n\", slot: \"0\", offset: 8, type: \"t_uint64\"}, {label: \"b\", slot: \"0\", offset: 16, type: \"t_uint64\"}] + .[2:])"
want 1 "c. a mid-struct insert fails and names the struct and both members" "struct T: member n was inserted before b" "moved from slot 0 offset 8 to slot 0 offset 16"
synth "$T.bytes = 96 | $T.members += [{label: \"d\", slot: \"2\", offset: 0, type: \"t_uint256\"}]"
want 0 "c. an append in a new slot passes"
synth "$U.members += [{label: \"y\", slot: \"0\", offset: 16, type: \"t_uint64\"}]"
want 0 "c. an append in the free bytes of the last slot passes"
synth "$T.members |= [.[1], .[0], .[2]]"
want 1 "c. a reorder fails and names the member" "struct T: member a was reordered"
synth "$T.members |= [.[0], .[2]]"
want 1 "c. a removal fails and names the member" "struct T: member b" "was removed"
synth "$T.members |= .[:2]"
want 1 "c. a removed last member fails" "struct T: member c" "was removed"
synth "$T.members[1].type = \"t_uint32\""
want 1 "c. a retype fails and names the member" "struct T: member b was retyped from t_uint64 to t_uint32"
synth "$T.members[2].slot = \"2\""
want 1 "c. a moved member fails" "struct T: member c moved from slot 1 offset 0 to slot 2 offset 0"
synth "del($T)"
want 1 "c. a struct that left the layout fails" "struct T: the struct is no longer in the layout"
synth "$E.bytes = 64 | $E.members += [{label: \"q\", slot: \"1\", offset: 0, type: \"t_uint256\"}]"
want 1 "c. an array-element struct that grows into a new slot fails" "struct E: it is an array element and its size changed from 32 to 64 bytes" "member q"
synth "$E.members += [{label: \"q\", slot: \"0\", offset: 16, type: \"t_uint64\"}]"
want 0 "c. an array-element struct that grows inside its last slot passes"
synth "$U.arrayElement = true | $U.bytes = 64 | $U.members += [{label: \"y\", slot: \"1\", offset: 0, type: \"t_uint256\"}]"
want 1 "c. a struct that became an array element may not have grown" "struct U: it is an array element"
# A new struct, and a new namespace, are not a break of anything the baseline holds.
synth '.nested.storage["t_struct(New)_storage"] = {bytes: 32, arrayElement: false, members: []} | .nested["x.y.Z"] = {}'
want 0 "c. a new struct and a new namespace pass"
# A baseline older than the nested section pins its structs in `structs`.
jq "{structs: {\"t_struct(T)_storage\": $T.members}}" "$TMP/base.json" >"$TMP/legacy.json"
jq "$T.members |= [.[1], .[0], .[2]]" "$TMP/base.json" >"$TMP/live.json"
check "$TMP/live.json" "$TMP/legacy.json" Synthetic
want 1 "c. a baseline with only the structs section is still compared" "struct T: member a was reordered"
check "$TMP/base.json" "$TMP/legacy.json" Synthetic
want 0 "c. the same layout extends a baseline with only the structs section"

# The migrations file: an entry covers a break only when contract, struct and both hashes match.
BREAK="$T.members |= [.[0], .[2]]"
jq "$BREAK" "$TMP/base.json" >"$TMP/broken.json"
from="$(python3 "$PY" hashes "$TMP/base.json" | awk '$3 == "T" {print $1}')"
to="$(python3 "$PY" hashes "$TMP/broken.json" | awk '$3 == "T" {print $1}')"
[[ ${#from} == 64 && ${#to} == 64 && "$from" != "$to" ]] || bad "the layout hashes of T are not two different sha256 values"
entry() { jq -n --arg c "$1" --arg s "$2" --arg f "$3" --arg t "$4" --arg m "$5" '{migrations: [{contract: $c, struct: $s, from: $f, to: $t, migration: $m}]}' >"$TMP/mig.json"; }
entry Synthetic T "$from" "$to" Synthetic.migrateV2
synth "$BREAK" "$TMP/mig.json"
want 0 "c. a declared break passes and names the migration" "struct T breaks the layout of base" "Synthetic.migrateV2"
entry Synthetic "t_struct(T)_storage" "$from" "$to" Synthetic.migrateV2
synth "$BREAK" "$TMP/mig.json"
want 0 "c. an entry may name the struct by its type id"
entry Other T "$from" "$to" Synthetic.migrateV2
synth "$BREAK" "$TMP/mig.json"
want 1 "c. an entry for another contract does not cover the break" "no migration declared for Synthetic"
entry Synthetic U "$from" "$to" Synthetic.migrateV2
synth "$BREAK" "$TMP/mig.json"
want 1 "c. an entry for another struct does not cover the break" "struct T: member b"
entry Synthetic T "$to" "$to" Synthetic.migrateV2
synth "$BREAK" "$TMP/mig.json"
want 1 "c. an entry with the wrong from hash does not cover the break" "struct T: member b"
entry Synthetic T "$from" "$from" Synthetic.migrateV2
synth "$BREAK" "$TMP/mig.json"
want 1 "c. an entry with the wrong to hash does not cover the break" "struct T: member b"
entry Synthetic T "$from" "$to" "migrate"
synth "$BREAK" "$TMP/mig.json"
want 2 "c. an entry whose migration is not Contract.function is an input error" "must be Contract.function"
entry Synthetic T "$from" "$to" ""
synth "$BREAK" "$TMP/mig.json"
want 2 "c. an entry with no migration is an input error" "lacks \`migration\`"
# --abi: the declared migration must be a function of the contract.
entry Synthetic T "$from" "$to" Synthetic.migrateV2
echo '{"abi": [{"type": "function", "name": "migrateV2"}]}' >"$TMP/abi.json"
rc=0; python3 "$PY" check --live "$TMP/broken.json" --base "$TMP/base.json" --contract Synthetic --migrations "$TMP/mig.json" --ref base --abi "$TMP/abi.json" >"$TMP/out" 2>&1 || rc=$?
want 0 "c. a declared migration that is in the ABI passes"
echo '{"abi": [{"type": "function", "name": "other"}]}' >"$TMP/abi.json"
rc=0; python3 "$PY" check --live "$TMP/broken.json" --base "$TMP/base.json" --contract Synthetic --migrations "$TMP/mig.json" --ref base --abi "$TMP/abi.json" >"$TMP/out" 2>&1 || rc=$?
want 1 "c. a declared migration that is not in the ABI fails" "Synthetic.migrateV2 is not a function of Synthetic"

# The solc `types` section becomes the nested section: AST ids stripped, array elements marked through nested
# arrays, structs behind a mapping and inside a struct included.
cat >"$TMP/raw.json" <<'JSON'
{"storage": [{"label": "s", "slot": "0", "offset": 0, "type": "t_struct(Root)11_storage"}],
 "types": {
  "t_uint256": {"encoding": "inplace", "label": "uint256", "numberOfBytes": "32"},
  "t_struct(Root)11_storage": {"encoding": "inplace", "label": "struct Root", "numberOfBytes": "160", "members": [
    {"label": "byId", "slot": "0", "offset": 0, "type": "t_mapping(t_uint256,t_struct(Held)22_storage)"},
    {"label": "grid", "slot": "1", "offset": 0, "type": "t_array(t_array(t_struct(Cell)33_storage)2_storage)2_storage"},
    {"label": "list", "slot": "5", "offset": 0, "type": "t_array(t_struct(Item)44_storage)dyn_storage"}]},
  "t_mapping(t_uint256,t_struct(Held)22_storage)": {"encoding": "mapping", "key": "t_uint256", "label": "m", "numberOfBytes": "32", "value": "t_struct(Held)22_storage"},
  "t_array(t_array(t_struct(Cell)33_storage)2_storage)2_storage": {"encoding": "inplace", "label": "a", "numberOfBytes": "128", "base": "t_array(t_struct(Cell)33_storage)2_storage"},
  "t_array(t_struct(Cell)33_storage)2_storage": {"encoding": "inplace", "label": "a", "numberOfBytes": "64", "base": "t_struct(Cell)33_storage"},
  "t_array(t_struct(Item)44_storage)dyn_storage": {"encoding": "dynamic_array", "label": "a", "numberOfBytes": "32", "base": "t_struct(Item)44_storage"},
  "t_struct(Held)22_storage": {"encoding": "inplace", "label": "struct Held", "numberOfBytes": "32", "members": [
    {"label": "inner", "slot": "0", "offset": 0, "type": "t_struct(Inner)55_storage"}]},
  "t_struct(Inner)55_storage": {"encoding": "inplace", "label": "struct Inner", "numberOfBytes": "32", "members": [
    {"label": "v", "slot": "0", "offset": 0, "type": "t_uint256"}]},
  "t_struct(Cell)33_storage": {"encoding": "inplace", "label": "struct Cell", "numberOfBytes": "32", "members": [
    {"label": "v", "slot": "0", "offset": 0, "type": "t_uint256"}]},
  "t_struct(Item)44_storage": {"encoding": "inplace", "label": "struct Item", "numberOfBytes": "32", "members": [
    {"label": "v", "slot": "0", "offset": 0, "type": "t_uint256"}]}
 }}
JSON
python3 "$PY" nested "$TMP/raw.json" >"$TMP/nested.json" || bad "the nested section of a raw layout could not be built"
jq -e '(keys == ["t_struct(Cell)_storage", "t_struct(Held)_storage", "t_struct(Inner)_storage", "t_struct(Item)_storage", "t_struct(Root)_storage"])
       and .["t_struct(Cell)_storage"].arrayElement and .["t_struct(Item)_storage"].arrayElement
       and (.["t_struct(Held)_storage"].arrayElement | not) and (.["t_struct(Root)_storage"].arrayElement | not)
       and .["t_struct(Root)_storage"].bytes == 160
       and .["t_struct(Held)_storage"].members == [{"label": "inner", "slot": "0", "offset": 0, "type": "t_struct(Inner)_storage"}]' \
  "$TMP/nested.json" >/dev/null || { cp "$TMP/nested.json" "$TMP/out"; bad "the nested section of a raw layout is wrong"; }
pass "the nested section holds every reachable struct, AST ids stripped, array elements marked"
[[ "$(python3 "$PY" labels "$TMP/raw.json")" == '["byId", "grid", "list"]' ]] || bad "the probe's root member labels were not read"
pass "the root member labels of a probe layout are read"
# Two structs of one name cannot share a snapshot key.
jq '.types["t_struct(Cell)99_storage"] = (.types["t_struct(Cell)33_storage"] | .members[0].label = "w")' "$TMP/raw.json" >"$TMP/raw2.json"
rc=0; python3 "$PY" nested "$TMP/raw2.json" >"$TMP/out" 2>&1 || rc=$?
want 2 "two different structs of one name are an input error" "share the type name"

# ── live: the same through the gate, the layout read from forge and the probe contracts ───────────────────────
if [[ "$LIVE" == 1 ]]; then
  rc=0; "$GATE" --baseline-dir "$BASE" >"$TMP/out" 2>&1 || rc=$?
  want 0 "live a. the gate passes on this tree against v0.8.0 with the migrations file" \
    "FlowQueue robotmoney.storage.FlowQueue: struct Request breaks the layout" \
    "FlowQueue robotmoney.storage.FlowQueue: struct Settlement breaks the layout" \
    "Rebalancer storage: struct StepParams breaks the layout" \
    "FlowQueue storage layout extends the layout of"
  rc=0; MIGRATIONS="$TMP/none.json" "$GATE" --baseline-dir "$BASE" >"$TMP/out" 2>&1 || rc=$?
  want 1 "live b. the gate fails against v0.8.0 with no migrations entry" \
    "struct Request: member limit" "struct Settlement: member depositBoundPrice" "struct StepParams: member keeperGrace" \
    "FlowQueue storage layout does not extend" "Rebalancer storage layout does not extend"
  rc=0; PROBE_SRC="contracts/test/helpers/NoSuchProbe.sol" "$GATE" >"$TMP/out" 2>&1 || rc=$?
  want 2 "live: a namespace with no probe contract is a tooling error" "has no layout probe"
  mkdir "$TMP/empty"
  rc=0; "$GATE" --baseline-dir "$TMP/empty" >"$TMP/out" 2>&1 || rc=$?
  want 2 "live: a baseline directory that compares nothing is a tooling error" "nothing was compared"
fi

(( ran >= 40 )) || { echo "FAIL only $ran cases ran" >&2; exit 1; }
echo "check-core-storage-layout.test: all $ran cases passed"
